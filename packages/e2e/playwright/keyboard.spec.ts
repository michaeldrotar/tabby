import { expect, test } from './fixtures'

test('edits window identity and uses native focus, keyboard selection, menus, and tab creation', async ({
  page,
}) => {
  await page.goto('/tab-manager/index.html')
  const switcher = page.locator('[data-window-picker-trigger]')
  await expect(page.getByRole('link', { name: 'Skip to tabs' })).toHaveCount(0)
  await expect(switcher).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(page.getByRole('button', { name: 'Edit window' })).toBeFocused()
  await page.keyboard.press('Enter')
  const name = page.getByRole('textbox', { name: 'Name', exact: true })
  await expect(name).toBeFocused()
  expect(
    await name.evaluate((input: HTMLInputElement) => [
      input.selectionStart,
      input.selectionEnd,
    ]),
  ).toEqual([0, 5])
  await name.fill('Working space')
  await expect(switcher).toContainText('Working space')
  await page.evaluate(async () => {
    await chrome.windows.update(1, { focused: true })
  })
  await expect(page.getByRole('form', { name: 'Name and icon' })).toBeVisible()
  await expect(
    page.getByRole('heading', { name: 'Name and icon' }),
  ).toHaveCount(0)
  await page.getByRole('button', { name: 'Code icon', exact: true }).click()
  await page
    .getByRole('button', { name: 'Green icon color', exact: true })
    .click()
  await page.getByRole('button', { name: 'Edit window' }).click()
  await expect(page.getByRole('form', { name: 'Name and icon' })).toHaveCount(0)
  await page.getByRole('button', { name: 'Edit window' }).click()
  await expect(name).toHaveValue('Working space')
  await page.getByRole('button', { name: 'Done', exact: true }).click()
  await expect(switcher).toContainText('Working space')
  await expect(page.getByRole('button', { name: 'Edit window' })).toBeFocused()
  const firstItem = page
    .locator('[data-group-option], [data-tab-option]')
    .first()
  const newTab = page.getByRole('button', { name: 'New tab', exact: true })
  const search = page.getByRole('button', { name: 'Search everything' })
  const settings = page.getByRole('button', { name: 'Settings', exact: true })
  const more = page.getByRole('button', { name: 'More actions' })
  await firstItem.focus()
  await page.keyboard.press('ArrowUp')
  await expect(switcher).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('button', { name: 'Edit window' })).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(switcher).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(firstItem).toBeFocused()
  await page.keyboard.press('End')
  await expect(newTab).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(search).toBeFocused()
  await page.keyboard.press('ArrowRight')
  await expect(settings).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(newTab).toBeFocused()
  await page.keyboard.press('ArrowDown')
  await expect(search).toBeFocused()
  await page.keyboard.press('ArrowLeft')
  await expect(more).toBeFocused()
  await page.keyboard.press('ArrowUp')
  await expect(newTab).toBeFocused()
  await page.keyboard.press('ControlOrMeta+a')
  const rows = page.locator('[data-tab-option]')
  const selected = page.locator('[data-tab-option][aria-selected="true"]')
  await expect(selected).toHaveCount(4)
  await page.keyboard.press('Escape')
  await expect(selected).toHaveCount(1)
  await rows.first().focus()
  await page.keyboard.press('Space')
  await page.keyboard.press('ArrowDown')
  await page.keyboard.press('Space')
  await expect(selected).toHaveCount(2)
  await page.keyboard.press('Shift+ArrowDown')
  await expect(selected).toHaveCount(3)
  const origin = await page.locator(':focus').getAttribute('aria-label')
  const originBounds = await page.locator(':focus').boundingBox()
  await page.keyboard.press('ContextMenu')
  await expect(
    page.getByRole('menuitem', { name: 'Close 3 tabs', exact: true }),
  ).toBeFocused()
  const menuBounds = await page
    .getByRole('menu', { name: 'Selection actions' })
    .boundingBox()
  expect(Math.abs(menuBounds!.x - originBounds!.x)).toBeLessThan(2)
  await page.keyboard.press('Escape')
  await expect(page.getByLabel(origin!, { exact: true })).toBeFocused()
  await expect(selected).toHaveCount(3)
  await page.keyboard.press('Escape')
  await expect(selected).toHaveCount(1)
  await newTab.focus()
  await expect(newTab).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(rows).toHaveCount(5)
  await expect(rows.last()).toBeFocused()
  await page.keyboard.press('Escape')
  await switcher.click()
  await expect(page.locator('[data-window-choice="1"]')).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(
    page.getByRole('button', { name: 'Search everything' }),
  ).toBeEnabled()
})
