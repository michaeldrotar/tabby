export const SEASONAL_THEMES_ENABLED = false

export const curatedThemes = themeCatalog.filter(
  (theme) => SEASONAL_THEMES_ENABLED || theme.collection !== 'Seasonal',
)

export const themeCollections = (
  ['Tonal', 'Colorful', 'Seasonal'] as const
).filter((collection) =>
  curatedThemes.some((theme) => theme.collection === collection),
)

export type ThemePresetId = (typeof themeCatalog)[number]['id']
export type ThemeIconId = Extract<
  (typeof themeCatalog)[number],
  { icon: string }
>['icon']

export const getThemeIconId = (preferences: {
  themePreset: ThemePresetId | null
  seasonalIconsEnabled: boolean
  seasonalIconSelections: SeasonalIconSelections
}): ThemeIconId | SeasonalIconId | undefined => {
  const theme = curatedThemes.find(
    (theme) => theme.id === preferences.themePreset,
  )
  if (!preferences.seasonalIconsEnabled || !theme || !('icon' in theme))
    return undefined
  const icon =
    theme.id === 'summer'
      ? preferences.seasonalIconSelections.summer
      : theme.icon
  return icon === 'off' ? undefined : icon
}

